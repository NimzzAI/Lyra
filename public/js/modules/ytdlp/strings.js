export function ys(key) {
  const lang = currentLang === "id" ? ID : EN;
  return lang[key] != null ? lang[key] : EN[key] != null ? EN[key] : key;
}

export function applyStaticStrings(root) {
  root.querySelectorAll("[data-ys]").forEach(function (el) {
    el.textContent = ys(el.getAttribute("data-ys"));
  });
  root.querySelectorAll("[data-ys-placeholder]").forEach(function (el) {
    el.setAttribute("placeholder", ys(el.getAttribute("data-ys-placeholder")));
  });
}
